	private static void GenerateEnumConverter(IncrementalGeneratorInitializationContext context, IncrementalValueProvider<(string?, List<Diagnostic>)> registryInfo)
	{
		var enums1 = context.SyntaxProvider.ForAttributeWithMetadataName(
			JsonEnumCastingAttrName,
			predicate: static (node, _) => true,
			transform: static (context, _) =>
			{
				var attr = context.Attributes[0];
				var enumType = attr.ConstructorArguments[0].Value as INamedTypeSymbol;
				var pascalCase = attr.ConstructorArguments[1].Value as bool? ?? true;
				var members = enumType.GetMembers().OfType<IFieldSymbol>().Where(m => m.ConstantValue is not null).ToArray();
				return (enumType, pascalCase, members);
			}).Collect();
		var enums2 = context.SyntaxProvider.ForAttributeWithMetadataName(
				JsonEnumAttrName,
				predicate: (s, e) => s is EnumDeclarationSyntax enumDeclaration,
				transform: (ctx, e) =>
				{
					if (ctx.TargetNode is not EnumDeclarationSyntax enumDeclaration)
						return default;
					INamedTypeSymbol? symbol = ctx.SemanticModel.GetDeclaredSymbol(enumDeclaration);
					if (symbol is null)
						return default;
					var pascalCase = ctx.Attributes[0].ConstructorArguments[0].Value as bool? ?? true;
					var members = symbol.GetMembers().OfType<IFieldSymbol>().ToArray();
					return (symbol, pascalCase, members);
				}
			).Collect();
		context.RegisterSourceOutput(registryInfo.Combine(enums1.Combine(enums2)), (spc, registryInfoAndEnumSymbols) =>
		{
			((var registryId, var diagnostics), var enumSymbolsAll) = registryInfoAndEnumSymbols;
			foreach (var diag in diagnostics)
				spc.ReportDiagnostic(diag);
			(var enums1, var enums2) = enumSymbolsAll;
			List<(INamedTypeSymbol Type, bool PascalCase, IFieldSymbol[] Members)> enums = new();
			foreach (var (enumType, pascalCase, members) in enums1)
			{
				enums.Add((enumType, pascalCase, members));
			}
			foreach (var (enumType, pascalCase, members) in enums2)
			{
				enums.Add((enumType, pascalCase, members));
			}
			if (string.IsNullOrEmpty(registryId))
				return;
			StringBuilder sb1 = new();
			StringBuilder sb2 = new();
			sb1.AppendLine($$"""
				// <auto-generated/>
				#nullable enable
					using System;
					using System.Runtime.CompilerServices;
					using System.Text.Json;
				
				namespace RhythmBase.{{registryId}}.Serialization;
				/// <summary>
				/// Provides extension methods for converting enum values to and from their JSON string representations.
				/// </summary>
				public static class EnumConverterExtensions
					{
						/// <summary>
						/// Provides extension methods for converting enums to and from string representations.
						/// </summary>
						extension(RhythmBase.Global.Serialization.EnumConverter)
						{
				""");
			foreach (var e in enums.OrderBy(i => i.Type.Name))
			{
				static string GetStringName(IFieldSymbol symbol, bool pascalCase)
				{
					if (symbol.GetAttributes().FirstOrDefault(a => IsAttribute(a, JsonAliasAttrName) && a.ConstructorArguments.Length == 1)?.ConstructorArguments[0].Value is not string alias)
						return pascalCase ? symbol.Name : ToLowerCamelCase(symbol.Name);
					else
						return alias;
				}
				bool pascalCase = e.PascalCase;
				string fullName = e.Type.ToDisplayString();

				// TryParse(string)
				sb1.AppendLine($$"""
						/// <summary>
						/// Attempts to parse the specified string value to a <see cref="{{fullName}}"/> enum value.
						/// </summary>
						/// <param name="value">The string representation of the enum value.</param>
						/// <param name="result">When this method returns, contains the parsed <see cref="{{fullName}}"/> value if parsing succeeded; otherwise, the default value.</param>
						/// <returns><c>true</c> if parsing succeeded; otherwise, <c>false</c>.</returns>
						[MethodImpl(MethodImplOptions.AggressiveInlining)]
						public static bool TryParse(string? value, out {{fullName}} result)
						{
							switch(value) {
				""");
				foreach (var field in e.Members.OrderBy(i => i.Name))
				{
					sb1.AppendLine($$"""
								case "{{GetStringName(field, pascalCase)}}":
									result = {{field.ToDisplayString()}}; return true;
				""");
				}
				sb1.AppendLine("""
								default:
									result = default; return false;
							}
						}
				
				""");
				sb1.AppendLine();

				// TryParse(ReadOnlySpan<byte>)
				sb1.AppendLine($$"""
						/// <summary>
						/// Attempts to parse the specified UTF-8 byte span to a <see cref="{{fullName}}"/> enum value.
						/// </summary>
						/// <param name="value">The UTF-8 byte span representing the enum value.</param>
						/// <param name="result">When this method returns, contains the parsed <see cref="{{fullName}}"/> value if parsing succeeded; otherwise, the default value.</param>
						/// <returns><c>true</c> if parsing succeeded; otherwise, <c>false</c>.</returns>
						[MethodImpl(MethodImplOptions.AggressiveInlining)]
						public static bool TryParse(ReadOnlySpan<byte> value, out {{fullName}} result)
						{
				""");
				bool isFirst = true;
				foreach (var field in e.Members.OrderBy(i => i.Name))
				{
					sb1.AppendLine($$"""
							{{(isFirst ? "" : "else ")}}if (value.SequenceEqual("{{GetStringName(field, pascalCase)}}"u8))
							{
								result = {{field.ToDisplayString()}};
								return true;
							}
				""");
					isFirst = false;
				}
				sb1.AppendLine("""
							else
							{
								result = default;
								return false;
							}
						}

				""");

				// TryParse(ref Utf8JsonReader)
				sb1.AppendLine($$"""
						/// <summary>
						/// Attempts to parse the current JSON token value to a <see cref="{{fullName}}"/> enum value.
						/// Works with <see cref="System.Buffers.ReadOnlySequence{T}"/>-backed readers without allocating.
						/// </summary>
						/// <param name="reader">The JSON reader positioned at a string token.</param>
						/// <param name="result">When this method returns, contains the parsed <see cref="{{fullName}}"/> value if parsing succeeded; otherwise, the default value.</param>
						/// <returns><c>true</c> if parsing succeeded; otherwise, <c>false</c>.</returns>
						[MethodImpl(MethodImplOptions.AggressiveInlining)]
						public static bool TryParse(ref Utf8JsonReader reader, out {{fullName}} result)
						{
				""");
				isFirst = true;
				foreach (var field in e.Members.OrderBy(i => i.Name))
				{
					sb1.AppendLine($$"""
							{{(isFirst ? "" : "else ")}}if (reader.ValueTextEquals("{{GetStringName(field, pascalCase)}}"u8))
							{
								result = {{field.ToDisplayString()}};
								return true;
							}
				""");
					isFirst = false;
				}
				sb1.AppendLine("""
							else
							{
								result = default;
								return false;
							}
						}

				""");

				// ToEnumString
				sb2.AppendLine($$"""
					/// <summary>
					/// Converts the <see cref="{{fullName}}"/> enum value to its string representation.
					/// </summary>
					/// <param name="value">The enum value to convert.</param>
					/// <returns>The string representation of the enum value.</returns>
					[MethodImpl(MethodImplOptions.AggressiveInlining)]
					public static string ToEnumString(this {{fullName}} value) => value switch
					{
				""");
				foreach (var field in e.Members.OrderBy(i => i.Name))
				{
					sb2.AppendLine($"""
							{field.ToDisplayString()} => "{GetStringName(field, pascalCase)}",
				""");
				}
				sb2.AppendLine("""
							_ => value.ToString(),
					};
				""");


				// ToEnumUtf8String
				sb2.AppendLine($$"""
					/// <summary>
					/// Converts the <see cref="{{fullName}}"/> enum value to its UTF-8 string representation.
					/// </summary>
					/// <param name="value">The enum value to convert.</param>
					/// <returns>The string representation of the enum value.</returns>
					[MethodImpl(MethodImplOptions.AggressiveInlining)]
					public static ReadOnlySpan<byte> ToEnumUtf8String(this {{fullName}} value) => value switch
					{
				""");
				foreach (var field in e.Members.OrderBy(i => i.Name))
				{
					sb2.AppendLine($"""
							{field.ToDisplayString()} => "{GetStringName(field, pascalCase)}"u8,
				""");
				}
				sb2.AppendLine("""
							_ => System.Text.Encoding.UTF8.GetBytes(value.ToString()),
					};
				""");
			}
			sb1.AppendLine($$"""
					}
				{{sb2.ToString()}}
				}
				""");
			spc.AddSource($"EnumConverters.{registryId}.g.cs", sb1.ToString());
		});
	}
	private static IEnumerable<INamedTypeSymbol> GetDerivedTypes(INamedTypeSymbol baseType, Compilation compilation, bool includeReferences = false)
	{
		foreach (var t in GetAllTypes(compilation.GlobalNamespace))
			if (IsDerivedFrom(t, baseType))
				yield return t;
		if (!includeReferences) yield break;
		foreach (var asm in compilation.SourceModule.ReferencedAssemblySymbols)
			foreach (var t in GetAllTypes(asm.GlobalNamespace))
				if (IsDerivedFrom(t, baseType))
					yield return t;
	}
	private static bool IsDerivedFrom(INamedTypeSymbol? candidate, INamedTypeSymbol? baseType)
	{
		if (SymbolEqualityComparer.Default.Equals(candidate, baseType))
			return true;
		if (baseType?.TypeKind == TypeKind.Interface)
			return candidate?.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, baseType)) ?? false;
		for (var current = candidate?.BaseType;
				current != null && current.SpecialType != SpecialType.System_Object;
				current = current.BaseType)
		{
			if (SymbolEqualityComparer.Default.Equals(current, baseType))
				return true;
		}
		return false;
	}
	private static IEnumerable<INamedTypeSymbol> GetAllTypes(INamespaceSymbol namespaceSymbol)
	{
		foreach (var member in namespaceSymbol.GetMembers())
		{
			if (member is INamespaceSymbol nestedNS)
				foreach (var type in GetAllTypes(nestedNS))
					yield return type;
			else if (member is INamedTypeSymbol namedType)
			{
				yield return namedType;
				foreach (var nested in namedType.GetTypeMembers())
					yield return nested;
			}
		}
	}
	private static IEnumerable<INamedTypeSymbol> GetAllTypes(IAssemblySymbol assemblySymbol)
	{
		foreach (var module in assemblySymbol.Modules)
			foreach (var type in GetAllTypes(module.GlobalNamespace))
				yield return type;
	}

	private void GenerateTypeConverterRegistry(IncrementalGeneratorInitializationContext context, IncrementalValueProvider<((string?, List<Diagnostic>) Left, (ITypeSymbol, INamedTypeSymbol)[] Right)> incrementalValueProvider)
	{
		context.RegisterSourceOutput(incrementalValueProvider, (ctx, data) =>
	{
		var ((left, diagnostics), right) = data;
		foreach (var diag in diagnostics)
			ctx.ReportDiagnostic(diag);
		if (string.IsNullOrEmpty(left) || left == CoreNs)
			return;
		StringBuilder sb = new();
		sb.AppendLine($$"""
					// <auto-generated/>
					#nullable enable
					using System.Text.Json;
					using System.Text.Json.Serialization;
					using RhythmBase.Global.Serialization;

					namespace RhythmBase.{{left}}.Serialization;

					internal static partial class TypeConverterRegistry
					{
						private static class ConverterCache<T>
						{
							public static JsonConverter? Converter;
						}
						static TypeConverterRegistry()
						{
					""");
		foreach (var pair in right)
		{
			sb.AppendLine($$"""
							ConverterCache<{{pair.Item1.ToDisplayString()}}>.Converter = new {{pair.Item2.ToDisplayString()}}();
					""");
		}
		sb.AppendLine("""
						}
						public static T Read<T>(ref Utf8JsonReader reader, MetadataJsonSerializerOptions options)
						{
							if (ConverterCache<T>.Converter is MetadataJsonConverter<T> c1)
								return c1.Read(ref reader, typeof(T), options) ?? default!;
							if (ConverterCache<T>.Converter is JsonConverter<T> c2)
								return c2.Read(ref reader, typeof(T), options.JsonSerializerOptions) ?? default!;
							else
					#if DEBUG
								throw new NotImplementedException($"No converter found for type {typeof(T)}.");
					#else
								return default!;
					#endif
						}
						public static void Write<T>(Utf8JsonWriter writer, T value, MetadataJsonSerializerOptions options)
						{
							if (ConverterCache<T>.Converter is MetadataJsonConverter<T> c1)
								c1.Write(writer, value, options);
							else if (ConverterCache<T>.Converter is JsonConverter<T> c2)
								c2.Write(writer, value, options.JsonSerializerOptions);
							else
					#if DEBUG
								throw new NotImplementedException($"No converter found for type {typeof(T)}.");
					#else
								writer.WriteNullValue();
					#endif
						}
						public static void Write<T>(Utf8JsonWriter writer, ReadOnlySpan<byte> propertyName, T value, MetadataJsonSerializerOptions options)
						{
							writer.WritePropertyName(propertyName);
							Write(writer, value, options);
						}
					}
					""");
		ctx.AddSource($"TypeConverterRegistry.{left}.g.cs", sb.ToString());
	});
	}
	private static ITypeSymbol UnwarpNullable(ITypeSymbol type)
	{
		if (type.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T
			&& type is INamedTypeSymbol namedType
			&& namedType.TypeArguments.Length == 1)
			return namedType.TypeArguments[0];
		return type.WithNullableAnnotation(NullableAnnotation.NotAnnotated);
	}
	private void GenerateReadBody(Compilation compilation, StringBuilder sb, ClassGenCvtrInfo info, (ITypeSymbol, INamedTypeSymbol)[] classGenMap)
	{
		//sb.AppendLine("/*\n");


		sb.AppendLine("""
							if (base.Read(ref reader, ref value, options))
								return true;
					""");
		int index = 0;
		foreach (var prop in info.Properties.OrderBy(i => i.Property.Name))
		{
			var attrs = prop.Property.GetAttributes();
			var aliasAttrSmp = compilation.GetTypeByMetadataName(JsonAliasAttrName);
			var condAttrSmp = compilation.GetTypeByMetadataName(JsonConditionAttrName);
			var ignoreAttrSmp = compilation.GetTypeByMetadataName(JsonIgnoreAttrName);
			var jsonCvtrAttrSmp = compilation.GetTypeByMetadataName(JsonConverterAttrName);
			var timeCvtrAttrSmp = compilation.GetTypeByMetadataName(JsonTimeAttrName);
			var dftCvtrAttrSmp = compilation.GetTypeByMetadataName(JsonDefaultSerializerAttrName);
			var jsonEnumAttrSmp = compilation.GetTypeByMetadataName(JsonEnumAttrName);
			var jsonFlattenAttrSmp = compilation.GetTypeByMetadataName(JsonFlattenAttrName);

			bool shouldGenerate = GetShouldGenerate(prop, compilation);
			bool isNullable = prop.Property.Type.NullableAnnotation == NullableAnnotation.Annotated;
			if (shouldGenerate)
			{

				string alias = attrs.FirstOrDefault(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, aliasAttrSmp) && i.ConstructorArguments.Length == 1)?.ConstructorArguments[0].Value as string
						?? ToLowerCamelCase(prop.Property.ToDisplayParts().Last().ToString());
				string? condition = attrs.FirstOrDefault(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, condAttrSmp) && i.ConstructorArguments.Length == 1)?.ConstructorArguments[0].Value as string;
				INamedTypeSymbol? jsonCvtr = attrs.FirstOrDefault(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, jsonCvtrAttrSmp) && i.ConstructorArguments.Length == 1)?.ConstructorArguments[0].Value as INamedTypeSymbol;
				int? timeEnum = attrs.FirstOrDefault(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, timeCvtrAttrSmp) && i.ConstructorArguments.Length == 1)?.ConstructorArguments[0].Value as int?;

				string valueAccess = $"value.{prop.Property.ToDisplayParts().Last()}";
				{
					sb.AppendLine($$"""{{(index == 0 ? "" : "else ")}}if (reader.ValueTextEquals("{{alias}}"u8) && reader.Read())""");
					if (isNullable)
						sb.AppendLine($$"""
						{ if (reader.TokenType == JsonTokenType.Null) value.{{prop.Property.ToDisplayParts().Last()}} = null;
							else
				""");

					var type = UnwarpNullable(prop.Property.Type);

					GenerateReadProperty(new GeneratePropertyInfo(compilation, sb, classGenMap, index, attrs, dftCvtrAttrSmp, jsonEnumAttrSmp, isNullable, jsonCvtr, timeEnum, valueAccess, type, info.ClassType));
					if (isNullable)
						sb.Append("}");
					sb.AppendLine();
				}
			}
			// JsonFlatten: 展平子属性到当前层级
			AttributeData[] jsonFlattenAttrs = attrs.Where(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, jsonFlattenAttrSmp)).ToArray();
			if (jsonFlattenAttrs.Length > 0)
			{
				var parentType = UnwarpNullable(prop.Property.Type);
				bool parentIsValueType = parentType.TypeKind == TypeKind.Struct;
				foreach (var attr in jsonFlattenAttrs)
				{
					string subPropName = attr.ConstructorArguments[0].Value is string s ? s : throw new InvalidOperationException("Invalid JsonFlatten attribute: missing property name.");
					string aliasName = attr.ConstructorArguments[1].Value is string s2 ? s2 : ToLowerCamelCase(subPropName);
					int mode = attr.ConstructorArguments.Length >= 3 && attr.ConstructorArguments[2].Value is int m ? m : 3; // ReadWrite = 3
					if ((mode & 1) == 0) continue; // bit 0 = ReadOnly

					var subProp = parentType.GetMembers().FirstOrDefault(m => m.Name == subPropName) as IPropertySymbol;
					if (subProp is null) continue;

					bool subIsNullable = subProp.Type.NullableAnnotation == NullableAnnotation.Annotated;
					var subType = UnwarpNullable(subProp.Type);
					string parentAccess = $"value.{prop.Property.Name}";

					sb.AppendLine($$"""else if (reader.ValueTextEquals("{{aliasName}}"u8) && reader.Read())""");

					string flatValueAccess;
					if (parentIsValueType)
					{
						if (isNullable)
						{
							sb.AppendLine($$"""
							{ {{parentAccess}} ??= new();
							  var __flatParent = {{parentAccess}}.Value;
						""");
						}
						else
						{
							sb.AppendLine($$"""
							{ var __flatParent = {{parentAccess}};
						""");
						}
						flatValueAccess = $"__flatParent.{subPropName}";
					}
					else
					{
						if (isNullable)
						{
							sb.AppendLine($$"""
							{ {{parentAccess}} ??= new();
						""");
						}
						else
						{
							sb.AppendLine("{");
						}
						flatValueAccess = $"{parentAccess}.{subPropName}";
					}

					if (subIsNullable)
					{
						sb.AppendLine($$"""
						if (reader.TokenType == JsonTokenType.Null) {{flatValueAccess}} = null;
						else
					""");
					}

					// 查找子属性上的 JsonAlias / JsonTime / JsonConverter / JsonDefaultSerializer
					var subAttrs = subProp.GetAttributes();
					INamedTypeSymbol? subJsonCvtr = subAttrs.FirstOrDefault(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, jsonCvtrAttrSmp) && i.ConstructorArguments.Length == 1)?.ConstructorArguments[0].Value as INamedTypeSymbol;
					int? subTimeEnum = subAttrs.FirstOrDefault(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, timeCvtrAttrSmp) && i.ConstructorArguments.Length == 1)?.ConstructorArguments[0].Value as int?;
					GenerateReadProperty(new GeneratePropertyInfo(compilation, sb, classGenMap, index, subAttrs, dftCvtrAttrSmp, jsonEnumAttrSmp, subIsNullable, subJsonCvtr, subTimeEnum, flatValueAccess, subType, info.ClassType));
					if (parentIsValueType)
					{
						sb.AppendLine($$"""  {{parentAccess}} = __flatParent;""");
					}
					sb.AppendLine("}");
				}
			}

			index++;
		}
		sb.AppendLine("""
							else return false;
							return true;
					""");
	}

	private static bool GetShouldGenerate(PropertyGenerateConverterInfo prop, Compilation compilation)
	{
		var attrs = prop.Property.GetAttributes();
		var aliasAttrSmp = compilation.GetTypeByMetadataName(JsonAliasAttrName);
		var condAttrSmp = compilation.GetTypeByMetadataName(JsonConditionAttrName);
		var ignoreAttrSmp = compilation.GetTypeByMetadataName(JsonIgnoreAttrName);
		return prop.Property.SetMethod is not null &&
						prop.Property.ExplicitInterfaceImplementations.Length == 0 && // 不是显式接口实现或继承
						(
							(
								prop.Property.DeclaredAccessibility.HasFlag(Accessibility.Public) || // 公开属性，或
								attrs.FirstOrDefault(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, aliasAttrSmp)) is not null // 有 JsonAlias 属性
							) &&
							attrs.FirstOrDefault(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, ignoreAttrSmp)) is null // 没有 JsonIgnore 属性
						) &&
						(attrs.FirstOrDefault(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, condAttrSmp)) is not AttributeData i || i.ConstructorArguments.Length == 1 &&
							i.ConstructorArguments[0].Value is string s &&
							s != "false") // 没有 JsonCondition(false) 属性
						;
	}

	private class GeneratePropertyInfo
	{
		public GeneratePropertyInfo(Compilation compilation, StringBuilder sb, (ITypeSymbol, INamedTypeSymbol)[] classGenMap, int index, ImmutableArray<AttributeData> attrs, INamedTypeSymbol? dftCvtrAttrSmp, INamedTypeSymbol? jsonEnumAttrSmp, bool isNullable, INamedTypeSymbol? jsonCvtr, int? timeEnum, string valueAccess, ITypeSymbol type, INamedTypeSymbol containingType)
		{
			Compilation = compilation;
			StringBuilder = sb;
			ClassGenMap = classGenMap;
			Index = index;
			Attrs = attrs;
			DftCvtrAttrSmp = dftCvtrAttrSmp;
			JsonEnumAttrSmp = jsonEnumAttrSmp;
			IsNullable = isNullable;
			JsonCvtr = jsonCvtr;
			TimeEnum = timeEnum;
			ValueAccess = valueAccess;
			Type = type;
			ContainingType = containingType;
		}

		public Compilation Compilation { get; set; }
		public StringBuilder StringBuilder { get; set; }
		public (ITypeSymbol, INamedTypeSymbol)[] ClassGenMap { get; set; }
		public int Index { get; set; }
		public ImmutableArray<AttributeData> Attrs { get; }
		public INamedTypeSymbol? DftCvtrAttrSmp { get; }
		public INamedTypeSymbol? JsonEnumAttrSmp { get; }
		public bool IsNullable { get; }
		public INamedTypeSymbol? JsonCvtr { get; }
		public int? TimeEnum { get; }
		public string ValueAccess { get; }
		public ITypeSymbol Type { get; }
		public INamedTypeSymbol ContainingType { get; }
	}
	private void GenerateReadProperty(GeneratePropertyInfo info)
	{
		var jsonCvtr = info.JsonCvtr;
		var classGenMap = info.ClassGenMap;
		var valueAccess = info.ValueAccess;
		var type = info.Type;
		var isNullable = info.IsNullable;
		var timeEnum = info.TimeEnum;
		var sb = info.StringBuilder;
		var compilation = info.Compilation;
		var dftCvtrAttrSmp = info.DftCvtrAttrSmp;
		var jsonEnumAttrSmp = info.JsonEnumAttrSmp;
		var attrs = info.Attrs;
		var index = info.Index;
		// JsonUnit 单位转换
		var jsonUnitAttrSmp = compilation.GetTypeByMetadataName(JsonUnitAttrName);
		AttributeData[] unitAttrs = attrs.Where(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, jsonUnitAttrSmp)).ToArray();
		if (unitAttrs.Length > 0 && TryEmitUnitRead(info, unitAttrs))
			return;
		// 已注册转换器
		if (jsonCvtr is null && classGenMap.FirstOrDefault(i => i.Item1.Equals(type, SymbolEqualityComparer.Default)) is var (classGen, cvtr) && classGen is not null)
		{
			sb.Append($$"""{{valueAccess}} = TypeConverterRegistry.Read<{{type.ToDisplayString()}}>(ref reader, options);""");
		}
		// 自定义转换器
		else if (jsonCvtr is not null)
		{
			if (SymbolEqualityComparer.Default.Equals(jsonCvtr.BaseType.OriginalDefinition, compilation.GetTypeByMetadataName(MetadataJsonConverterTypeName)))
				sb.Append($$"""{{valueAccess}} = new {{jsonCvtr.ToDisplayString()}}().Read(ref reader, typeof({{type.ToDisplayString()}}), options);""");
			else
				sb.Append($$"""{{valueAccess}} = new {{jsonCvtr.ToDisplayString()}}().Read(ref reader, typeof({{type.ToDisplayString()}}), options.JsonSerializerOptions);""");
		}
		// 时间
		else if (timeEnum is int timeType)
		{
			switch (timeType)
			{
				case 0:
					sb.Append($"{valueAccess} = TimeSpan.FromMilliseconds(reader.GetDouble());");
					break;
				case 1:
					sb.Append($"{valueAccess} = TimeSpan.FromSeconds(reader.GetDouble());");
					break;
				default:
					sb.Append($$"""{ throw new NotImplementedException(); /* Unsupported time converter type: {{timeType}} */ }""");
					break;
			}
		}
		// 枚举
		else if (type.TypeKind == TypeKind.Enum)
		{
			if (
				!attrs.Any(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, dftCvtrAttrSmp)) &&
				type.GetAttributes().Any(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, jsonEnumAttrSmp)))
				sb.Append($$"""{ if (global::RhythmBase.Global.Serialization.EnumConverter.TryParse(ref reader, out {{type.ToDisplayString()}} enumValue{{index}})) {{valueAccess}} = enumValue{{index}}; else return false; }""");
			else
				// - 非枚举或无需序列化器
				sb.Append($$"""{{valueAccess}} = ({{type.ToDisplayString()}})reader.GetInt64();""");
		}
		// 默认类型
		else if (type.SpecialType is not SpecialType.None)
			sb.Append($$"""{{valueAccess}} = reader.Get{{GetJsonReadMethod(type)}}(){{((GetJsonReadMethod(type) == "String" && !isNullable) ? " ?? \"\"" : "")}};""");
		// 其他
		else if (IsConcreteEnumerable(type) is ITypeSymbol elementType)
		{
			string listType = $"System.Collections.Generic.List<{elementType.ToDisplayString()}>";
			sb.AppendLine($$"""
					{
						var list = new {{listType}}();
						if (reader.TokenType == JsonTokenType.StartArray)
						{
							while (reader.Read() && reader.TokenType != JsonTokenType.EndArray)
							{
			""");
			if (elementType.SpecialType is not SpecialType.None)
				sb.Append($$"""  var elementValue = reader.Get{{GetJsonReadMethod(elementType)}}(){{((GetJsonReadMethod(elementType) == "String" && !isNullable) ? " ?? \"\"" : "")}};""");
			else if (elementType.TypeKind == TypeKind.Enum)
				if (
					elementType.GetAttributes().Any(i => SymbolEqualityComparer.Default.Equals(i.AttributeClass, jsonEnumAttrSmp)))
					sb.Append($$"""  global::RhythmBase.Global.Serialization.EnumConverter.TryParse(reader.GetString(), out {{elementType.ToDisplayString()}} elementValue);""");
				else
					// - 非枚举或无需序列化器
					sb.AppendLine($$"""					var elementValue = ({{elementType.ToDisplayString()}})reader.GetInt64();""");
			else
				sb.Append($$"""					var elementValue = TypeConverterRegistry.Read<{{elementType.ToDisplayString()}}>(ref reader, options);""");
			sb.AppendLine($$"""
								list.Add(elementValue);
							}
						}
						{{valueAccess}} = [..list];
					}
			""");
		}
		else
			sb.Append($$"""{{valueAccess}} = TypeConverterRegistry.Read<{{type.ToDisplayString()}}>(ref reader, options);""");
	}
	private static string FloatLiteral(object? value)
	{
		float f = Convert.ToSingle(value, System.Globalization.CultureInfo.InvariantCulture);
		return f.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "f";
	}

	// Returns false when the property type is not supported by JsonUnit, so the caller falls back
	// to the regular read path.
	private bool TryEmitUnitRead(GeneratePropertyInfo info, AttributeData[] unitAttrs)
	{
		var sb = info.StringBuilder;
		var type = info.Type;
		var jsonCvtr = info.JsonCvtr;
		var classGenMap = info.ClassGenMap;
		var compilation = info.Compilation;
		string? raw;
		if (jsonCvtr is not null)
		{
			raw = SymbolEqualityComparer.Default.Equals(jsonCvtr.BaseType.OriginalDefinition, compilation.GetTypeByMetadataName(MetadataJsonConverterTypeName))
				? $"new {jsonCvtr.ToDisplayString()}().Read(ref reader, typeof({type.ToDisplayString()}), options)"
				: $"new {jsonCvtr.ToDisplayString()}().Read(ref reader, typeof({type.ToDisplayString()}), options.JsonSerializerOptions)";
		}
		else if (classGenMap.Any(i => i.Item1.Equals(type, SymbolEqualityComparer.Default)))
			raw = $"TypeConverterRegistry.Read<{type.ToDisplayString()}>(ref reader, options)";
		else if (type.SpecialType == SpecialType.System_Single)
			raw = "reader.GetSingle()";
		else if (type.SpecialType == SpecialType.System_Double)
			raw = "reader.GetDouble()";
		else if (type.SpecialType == SpecialType.System_Int32)
			raw = "reader.GetInt32()";
		else if (type.SpecialType == SpecialType.System_Int64)
			raw = "reader.GetInt64()";
		else
			return false;

		sb.Append("{ ");
		AttributeData? fn = unitAttrs.FirstOrDefault(a => a.ConstructorArguments.Length == 2 && a.ConstructorArguments[0].Value is string && a.ConstructorArguments[1].Value is string);
		if (fn is AttributeData f)
		{
			string scaleFn = (string)f.ConstructorArguments[0].Value!;
			sb.Append($"{info.ValueAccess} = {info.ContainingType.ToDisplayString()}.{scaleFn}({raw});");
		}
		else
		{
			AttributeData[] members = unitAttrs.Where(a => a.ConstructorArguments.Length >= 2 && a.ConstructorArguments[0].Value is string).ToArray();
			if (members.Length > 0)
			{
				string tmp = $"__unit{info.Index}";
				sb.Append($"var {tmp} = {raw};");
				foreach (AttributeData a in members)
				{
					string member = (string)a.ConstructorArguments[0].Value!;
					string m = FloatLiteral(a.ConstructorArguments[1].Value);
					string b = a.ConstructorArguments.Length >= 3 ? FloatLiteral(a.ConstructorArguments[2].Value) : "0f";
					sb.Append($"{tmp}.{member} = {tmp}.{member} * {m} + {b};");
				}
				sb.Append($"{info.ValueAccess} = {tmp};");
			}
			else
			{
				AttributeData s = unitAttrs[0];
				string sm = FloatLiteral(s.ConstructorArguments[0].Value);
				string sbv = s.ConstructorArguments.Length >= 2 ? FloatLiteral(s.ConstructorArguments[1].Value) : "0f";
				sb.Append($"{info.ValueAccess} = ({type.ToDisplayString()})({raw} * {sm} + {sbv});");
			}
		}
		sb.Append(" }");
		return true;
	}

	private void EmitNormalWrite(StringBuilder sb, string alias, string expr, ITypeSymbol type, INamedTypeSymbol? jsonCvtr, (ITypeSymbol, INamedTypeSymbol)[] classGenMap, Compilation compilation)
	{
		if (jsonCvtr is not null)
		{
			string arg = SymbolEqualityComparer.Default.Equals(jsonCvtr.BaseType.OriginalDefinition, compilation.GetTypeByMetadataName(MetadataJsonConverterTypeName))
				? "options"
				: "options.JsonSerializerOptions";
			sb.Append($"writer.WritePropertyName(\"{alias}\"u8); new {jsonCvtr.ToDisplayString()}().Write(writer, {expr}, {arg});");
		}
		else if (classGenMap.Any(i => i.Item1.Equals(type, SymbolEqualityComparer.Default)))
			sb.Append($"writer.WritePropertyName(\"{alias}\"u8); TypeConverterRegistry.Write(writer, {expr}, options);");
		else
			sb.Append($"writer.Write{GetJsonWriterMethod(type)}(\"{alias}\"u8, {expr});");
	}

	private void EmitUnitWrite(StringBuilder sb, string alias, string valueAccess, ITypeSymbol type, INamedTypeSymbol? jsonCvtr, AttributeData[] unitAttrs, (ITypeSymbol, INamedTypeSymbol)[] classGenMap, Compilation compilation, INamedTypeSymbol containingType, int index, bool hasCondition)
	{
		string open = hasCondition ? "{ " : "";
		string close = hasCondition ? " }" : "";
		AttributeData? fn = unitAttrs.FirstOrDefault(a => a.ConstructorArguments.Length == 2 && a.ConstructorArguments[0].Value is string && a.ConstructorArguments[1].Value is string);
		if (fn is AttributeData f)
		{
			string reverse = (string)f.ConstructorArguments[1].Value!;
			string tmp = $"__unit{index}";
			sb.Append(open);
			sb.Append($"var {tmp} = {containingType.ToDisplayString()}.{reverse}({valueAccess});");
			EmitNormalWrite(sb, alias, tmp, type, jsonCvtr, classGenMap, compilation);
			sb.Append(close);
			return;
		}
		AttributeData[] members = unitAttrs.Where(a => a.ConstructorArguments.Length >= 2 && a.ConstructorArguments[0].Value is string).ToArray();
		if (members.Length > 0)
		{
			string tmp = $"__unit{index}";
			sb.Append(open);
			sb.Append($"var {tmp} = {valueAccess};");
			foreach (AttributeData a in members)
			{
				string member = (string)a.ConstructorArguments[0].Value!;
				string m = FloatLiteral(a.ConstructorArguments[1].Value);
				string b = a.ConstructorArguments.Length >= 3 ? FloatLiteral(a.ConstructorArguments[2].Value) : "0f";
				sb.Append($"{tmp}.{member} = ({tmp}.{member} - {b}) / {m};");
			}
			EmitNormalWrite(sb, alias, tmp, type, jsonCvtr, classGenMap, compilation);
			sb.Append(close);
			return;
		}
		AttributeData s = unitAttrs[0];
		string sm = FloatLiteral(s.ConstructorArguments[0].Value);
		string sbv = s.ConstructorArguments.Length >= 2 ? FloatLiteral(s.ConstructorArguments[1].Value) : "0f";
		string expr = $"({valueAccess} - {sbv}) / {sm}";
		if (jsonCvtr is not null)
		{
			string tmp = $"__unit{index}";
			sb.Append(open);
			sb.Append($"var {tmp} = ({type.ToDisplayString()})({expr});");
			EmitNormalWrite(sb, alias, tmp, type, jsonCvtr, classGenMap, compilation);
			sb.Append(close);
		}
		else
		{
			sb.Append($"{open}writer.Write{GetJsonWriterMethod(type)}(\"{alias}\"u8, {expr});{close}");
		}
	}

